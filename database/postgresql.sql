-- PostgreSQL schema for CLASS SPHERE; preserves the supplied MySQL schema semantics.
CREATE TABLE IF NOT EXISTS academic_years (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year_number SMALLINT NOT NULL UNIQUE,
  label VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS semesters (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year_id SMALLINT NOT NULL,
  semester_number SMALLINT NOT NULL,
  CONSTRAINT uq_year_semester UNIQUE (academic_year_id, semester_number),
  CONSTRAINT fk_sem_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id)
);

CREATE TABLE IF NOT EXISTS units (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  semester_id SMALLINT NOT NULL,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(180) NOT NULL,
  description TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_unit_semester FOREIGN KEY (semester_id) REFERENCES semesters(id)
);

CREATE TABLE IF NOT EXISTS lecturers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS timetable_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id INTEGER NOT NULL,
  day_of_week VARCHAR(12) NOT NULL,
  starts_at TIME NOT NULL,
  ends_at TIME NOT NULL,
  lecturer_id INTEGER NULL,
  venue VARCHAR(80) NULL,
  class_type VARCHAR(20) NULL,
  source_label VARCHAR(80) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_timetable_unit FOREIGN KEY (unit_id) REFERENCES units(id),
  CONSTRAINT fk_timetable_lecturer FOREIGN KEY (lecturer_id) REFERENCES lecturers(id)
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  admission_number VARCHAR(50) NULL UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role TEXT CHECK (role IN ('student','admin')) NOT NULL DEFAULT 'student',
  status TEXT CHECK (status IN ('pending_email','active','suspended')) NOT NULL DEFAULT 'pending_email',
  email_verified_at TIMESTAMPTZ NULL,
  directory_public SMALLINT NOT NULL DEFAULT 0,
  public_display_name VARCHAR(120) NULL,
  profile_photo_key VARCHAR(512) NULL,
  nonessential_email_consent_at TIMESTAMPTZ NULL,
  email_unsubscribed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_user_admission_role CHECK (
    (role = 'admin' AND admission_number IS NULL) OR
    (role = 'student' AND admission_number LIKE 'SB62/%')
  ),
  admin_approved_at TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS app_sessions (
  session_id VARCHAR(128) PRIMARY KEY,
  session_data TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS email_verification_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_verify_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  body TEXT NOT NULL,
  category TEXT CHECK (category IN ('academic','timetable','event','general')) NOT NULL DEFAULT 'general',
  audience TEXT CHECK (audience IN ('public','students')) NOT NULL DEFAULT 'students',
  status TEXT CHECK (status IN ('draft','published','archived')) NOT NULL DEFAULT 'draft',
  priority TEXT CHECK (priority IN ('normal','urgent')) NOT NULL DEFAULT 'normal',
  author_id BIGINT NOT NULL,
  published_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_announcement_author FOREIGN KEY (author_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  announcement_id BIGINT NULL,
  category TEXT CHECK (category IN ('academic','timetable','event','general')) NOT NULL,
  priority TEXT CHECK (priority IN ('normal','urgent')) NOT NULL DEFAULT 'normal',
  title VARCHAR(200) NOT NULL,
  body TEXT NOT NULL,
  read_at TIMESTAMPTZ NULL,
  dismissed_at TIMESTAMPTZ NULL,
  snoozed_until TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_notification_announcement FOREIGN KEY (announcement_id) REFERENCES announcements(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS notification_preferences (
  user_id BIGINT PRIMARY KEY,
  academic_enabled SMALLINT NOT NULL DEFAULT 1,
  timetable_enabled SMALLINT NOT NULL DEFAULT 1,
  event_enabled SMALLINT NOT NULL DEFAULT 1,
  general_enabled SMALLINT NOT NULL DEFAULT 1,
  quiet_start TIME NULL,
  quiet_end TIME NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notification_pref_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id INTEGER NOT NULL,
  title VARCHAR(200) NOT NULL,
  resource_type TEXT CHECK (resource_type IN ('lecture_notes','past_paper','assignment','practical','other')) NOT NULL,
  storage_key VARCHAR(512) NOT NULL UNIQUE,
  original_filename VARCHAR(255) NOT NULL,
  mime_type VARCHAR(120) NOT NULL,
  file_size_bytes BIGINT NOT NULL,
  uploaded_by BIGINT NOT NULL,
  visibility TEXT CHECK (visibility IN ('students','public')) NOT NULL DEFAULT 'students',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_resource_unit FOREIGN KEY (unit_id) REFERENCES units(id),
  CONSTRAINT fk_resource_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id),
  approval_status TEXT NOT NULL DEFAULT 'approved' CHECK (approval_status IN ('pending','approved','rejected'))
);

CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NULL,
  venue VARCHAR(160) NULL,
  status TEXT CHECK (status IN ('draft','published','cancelled','archived')) NOT NULL DEFAULT 'draft',
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_event_creator FOREIGN KEY (created_by) REFERENCES users(id),
  event_type TEXT NOT NULL DEFAULT 'event' CHECK (event_type IN ('event','cat','exam'))
);

CREATE TABLE IF NOT EXISTS gallery_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  category VARCHAR(80) NULL,
  storage_key VARCHAR(512) NOT NULL UNIQUE,
  alt_text VARCHAR(200) NOT NULL,
  permission_confirmed SMALLINT NOT NULL DEFAULT 0,
  status TEXT CHECK (status IN ('draft','published','archived')) NOT NULL DEFAULT 'draft',
  uploaded_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_gallery_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS ai_announcement_drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prompt TEXT NOT NULL,
  title VARCHAR(200) NULL,
  body TEXT NULL,
  funny_version TEXT NULL,
  professional_version TEXT NULL,
  whatsapp_version TEXT NULL,
  provider VARCHAR(80) NOT NULL,
  model VARCHAR(120) NULL,
  status TEXT CHECK (status IN ('draft','published','discarded')) NOT NULL DEFAULT 'draft',
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ai_draft_author FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS email_campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject VARCHAR(250) NOT NULL,
  body TEXT NOT NULL,
  category TEXT CHECK (category IN ('essential','nonessential')) NOT NULL,
  idempotency_key CHAR(36) NOT NULL,
  created_by BIGINT NOT NULL,
  confirmed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_email_campaign_author FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT uq_email_idempotency UNIQUE (created_by, idempotency_key)
);

CREATE TABLE IF NOT EXISTS email_recipients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  recipient_email VARCHAR(254) NOT NULL,
  provider_message_id VARCHAR(255) NULL,
  status TEXT CHECK (status IN ('queued','sent','delivered','failed','bounced','unsubscribed')) NOT NULL DEFAULT 'queued',
  error_summary VARCHAR(500) NULL,
  attempted_at TIMESTAMPTZ NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_email_recipient_campaign FOREIGN KEY (campaign_id) REFERENCES email_campaigns(id) ON DELETE CASCADE,
  CONSTRAINT fk_email_recipient_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT uq_campaign_recipient UNIQUE (campaign_id, user_id)
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NULL,
  action VARCHAR(120) NOT NULL,
  entity_type VARCHAR(80) NOT NULL,
  entity_id VARCHAR(80) NULL,
  context_json JSONB NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_name VARCHAR(160) NOT NULL,
  sender_email VARCHAR(254) NOT NULL,
  subject VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  status TEXT CHECK (status IN ('new','reviewed','closed')) NOT NULL DEFAULT 'new',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS class_popup_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  timetable_entry_id BIGINT NOT NULL,
  class_date DATE NOT NULL,
  dismissed_at TIMESTAMPTZ NULL,
  snoozed_until TIMESTAMPTZ NULL,
  CONSTRAINT uq_popup_class_user UNIQUE (user_id, timetable_entry_id, class_date),
  CONSTRAINT fk_popup_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_popup_timetable FOREIGN KEY (timetable_entry_id) REFERENCES timetable_entries(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS email_unsubscribe_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_unsubscribe_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS chat_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_chat_groups_name UNIQUE (name),
  CONSTRAINT fk_chat_groups_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS chat_group_members (
  group_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  added_by BIGINT NOT NULL,
  added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (group_id,user_id),
  CONSTRAINT fk_chat_group_members_group FOREIGN KEY (group_id) REFERENCES chat_groups(id) ON DELETE CASCADE,
  CONSTRAINT fk_chat_group_members_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_chat_group_members_adder FOREIGN KEY (added_by) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  chat_type TEXT CHECK (chat_type IN ('general','individual','group')) NOT NULL,
  sender_id BIGINT NOT NULL,
  recipient_id BIGINT NULL,
  group_id BIGINT NULL,
  body VARCHAR(2000) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_chat_messages_recipient FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_chat_messages_group FOREIGN KEY (group_id) REFERENCES chat_groups(id) ON DELETE CASCADE,
  reply_to_message_id BIGINT NULL, CONSTRAINT fk_chat_messages_reply FOREIGN KEY (reply_to_message_id) REFERENCES chat_messages(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS site_settings (
  setting_key VARCHAR(80) PRIMARY KEY,
  setting_value TEXT NULL,
  updated_by BIGINT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_site_setting_actor FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
);

